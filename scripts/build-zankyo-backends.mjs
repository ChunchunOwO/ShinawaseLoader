#!/usr/bin/env node
// Reproducible source-only ports; the original checkout is a build input.
import { execFileSync } from 'node:child_process';
import { createRequire } from 'node:module';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve, posix } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(fileURLToPath(new URL('..', import.meta.url)));
const echo = process.argv[2] || process.env.ECHO_GPUI_ECHO_ROOT;
if (!echo) throw new Error('Usage: build-zankyo-backends.mjs "<ECHO_SOURCE>" [commit]');
const git = (...args) => execFileSync('git', ['-C', echo, ...args], { encoding: 'utf8', maxBuffer: 8 * 1024 * 1024 });
const commit = git('rev-parse', process.argv[3] || '0e4a90f5^').trim();
const { build } = createRequire(resolve(echo, 'package.json'))('esbuild');
const cache = new Map();
const show = path => {
  if (!cache.has(path)) cache.set(path, git('show', `${commit}:${path}`));
  return cache.get(path);
};
const boundary = resolve(root, 'scripts/zankyo-backends/boundary.ts');
const redirects = new Map([
  ['src/main/accounts/AccountService.ts', boundary], ['src/main/accounts/SpotifyAuthService.ts', boundary],
  ['src/main/accounts/TidalAuthService.ts', boundary], ['src/main/app/appSettings.ts', boundary],
  ['src/main/network/networkFetch.ts', boundary], ['src/main/network/networkAccessPolicy.ts', boundary],
  ['src/main/qobuz/QobuzAuthService.ts', resolve(root, 'scripts/zankyo-backends/qobuz.ts')],
]);
const destinations = {
  streaming: 'examples/ECHO-Streaming/echomod/zankyo',
  lyrics: 'examples/ECHO-LyricsMatchWhitebox/echomod/zankyo',
};
for (const [name, directory] of Object.entries(destinations)) {
  const destination = resolve(root, directory);
  mkdirSync(destination, { recursive: true });
  const result = await build({
    entryPoints: [resolve(root, `scripts/zankyo-backends/${name}.ts`)],
    bundle: true, platform: 'node', format: 'cjs', target: 'node22', write: false,
    define: { 'import.meta.url': '__filename' },
    banner: { js: `// Generated by scripts/build-zankyo-backends.mjs.\n// ECHO sources (c) 2026 Moekotori, commit ${commit}.\n// Reused under the workspace owner's explicit porting permission. See UPSTREAM-LICENSE.txt.` },
    plugins: [{
      name: 'echo-source',
      setup(build) {
        build.onResolve({ filter: /^echo-source:/ }, args => ({ path: args.path.slice(12), namespace: 'echo-source' }));
        build.onResolve({ filter: /^\./, namespace: 'echo-source' }, args => {
          const path = posix.normalize(posix.join(posix.dirname(args.importer), args.path)) + (posix.extname(args.path) ? '' : '.ts');
          return redirects.has(path) ? { path: redirects.get(path) } : { path, namespace: 'echo-source' };
        });
        build.onLoad({ filter: /.*/, namespace: 'echo-source' }, args => {
          let contents = show(args.path);
          if (args.path === 'src/main/streaming/providers/NeteaseStreamingProvider.ts') {
            // Preserve full-track authorization checks before the legacy mapper drops trial metadata.
            if (contents.split('const url = text(entry.url);').length !== 3 ||
                !contents.includes('const url = text(source.url);')) throw new Error('NetEase playback boundary changed');
            contents = contents.replaceAll('const url = text(entry.url);', 'const url = entry.freeTrialInfo ? null : text(entry.url);')
              .replace('const url = text(source.url);', 'const url = source.freeTrialInfo ? null : text(source.url);');
          }
          return { contents, loader: 'ts', resolveDir: resolve(echo) };
        });
      },
    }],
  });
  writeFileSync(resolve(destination, 'providers.cjs'), result.outputFiles[0].contents);
  writeFileSync(resolve(destination, 'UPSTREAM-LICENSE.txt'), show('LICENSE'));
  const notices = ['opencc-js/LICENSE', 'opencc-js/THIRD_PARTY_LICENSES.md', '@xmldom/xmldom/LICENSE']
    .map(file => `## ${file}\n\n${readFileSync(resolve(echo, 'node_modules', file), 'utf8')}`).join('\n\n');
  writeFileSync(resolve(destination, 'THIRD-PARTY-NOTICES.txt'), notices);
  console.log(`${name}: ${result.outputFiles[0].contents.length} bytes, ECHO ${commit}`);
}
// Preserve the exact existing title normalization and its OpenCC notices.
const whitebox = readFileSync(resolve(root, 'examples/ECHO-LyricsMatchWhitebox/echomod/mod.js'), 'utf8');
const start = whitebox.indexOf('/* NORMALIZER_START */');
const end = whitebox.indexOf('/** Text normalization options');
if (start < 0 || end < start) throw new Error('Lyrics normalizer source markers changed');
writeFileSync(resolve(root, destinations.lyrics, 'normalizer.cjs'),
  '// Generated from the Electron entry; rebuild with scripts/build-zankyo-backends.mjs.\n' +
  whitebox.slice(start, end) + '\nmodule.exports = { createLyricsNormalizer };\n');
