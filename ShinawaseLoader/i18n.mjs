export const normalizeLocale = (value) => {
  const text = String(value || '').trim().toLowerCase();
  if (text === 'zh' || text.startsWith('zh-') || text.startsWith('zh_')) return 'zh';
  if (text === 'en' || text.startsWith('en-') || text.startsWith('en_')) return 'en';
  return null;
};
